def recognize_text(text: str) -> list:
    """
    文字识别降级方案：关键词匹配本地食物表。
    未命中时按"普通一餐"估算。
    返回 [{name, portion, calories, protein, fat, carbs, fiber, sodium, confidence}]
    """
    results = []
    matched = set()
    for name, aliases, grams, cal, protein, fat, carbs, fiber, sodium in FOODS:
        for alias in aliases:
            if alias in text and name not in matched:
                matched.add(name)
                results.append({
                    "name": name,
                    "portion": f"约 {grams}g",
                    "calories": cal,
                    "protein": protein,
                    "fat": fat,
                    "carbs": carbs,
                    "fiber": fiber,
                    "sodium": sodium,
                    "confidence": 0.7,
                })
                break

    if not results:
        # 无法识别：按常见一餐估算
        results.append({
            "name": text[:20] or "未知食物",
            "portion": "1 份（估算）",
            "calories": 500,
            "protein": 18.0,
            "fat": 15.0,
            "carbs": 70.0,
            "fiber": 3.0,
            "sodium": 600,
            "confidence": 0.3,
        })
    return results


def guess_meal_type(text: str) -> str:
    if any(k in text for k in ["早", "早餐", " morning"]):
        return "早餐"
    if any(k in text for k in ["晚", "晚餐"]):
        return "晚餐"
    if any(k in text for k in ["加餐", "零食", "下午茶"]):
        return "加餐"
    return "午餐"
